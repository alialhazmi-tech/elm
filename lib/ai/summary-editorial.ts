export function validateExcerpt(value: unknown, title: string): string {
  const text = typeof value === "string" ? value.replace(/\s+/gu, " ").trim() : "";
  const normalize = (s: string) => s.replace(/[\p{P}\p{Z}\p{M}]/gu, "");
  if (!text || text.length > 180 || !/[\p{L}\p{N}]/u.test(text)) {
    throw new EditorialOutputError("لم يكتمل الموجز ضمن 180 حرفًا. أعد توليده؛ لم يُقتطع النص تلقائيًا.");
  }
  if (normalize(text) === normalize(title) || /^(?:يتناول (?:هذا )?(?:المقال|التقرير|النص)|يسلط (?:هذا )?(?:المقال|التقرير|النص) الضوء|تعرف على|اكتشف)/u.test(text)) {
    throw new EditorialOutputError("الموجز يكرر العنوان أو يصف المادة بدل تلخيصها. أعد التوليد للحصول على خلاصة من المتن.");
  }
  return text;
}
